"""Render paper tables from completed ZOH aggregates; never train or recompute metrics.

Run from any working directory:
    python /absolute/path/to/this/render_paper_tables.py

Both grids must be complete and match the adjacent frozen protocol before any
output is written. Historical aggregates are deliberately not accepted by CLI.
Only the Python standard library is required.
"""

import argparse
import hashlib
import json
import math
from pathlib import Path
import statistics


DIRECTORY = Path(__file__).resolve().parent
SEEDS = (42, 7, 123)
GRIDS = {"base": ("基础", (9, 7, 5)), "refined": ("加密", (17, 13, 9))}
SPLITS = {"validation": "验证集", "id_test": "ID 测试", "control_ood": "控制 OOD"}
MODELS = {"data_only": "数据模型", "physics_constrained": "物理约束模型"}
TABLE_METRICS = (
    "rollout_rmse_c",
    "final_rmse_mean_c",
    "implicit_physics_residual_rmse_c",
)
ALL_METRICS = (
    "rollout_rmse_c",
    "trajectory_rmse_mean_c",
    "trajectory_rmse_p95_c",
    "final_rmse_mean_c",
    "maximum_error_mean_c",
    "implicit_physics_residual_rmse_c",
)
INPUT_NAME = "three_dimensional_action_audit_metrics.json"


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def require(condition, message):
    if not condition:
        raise ValueError(message)


def finite_number(value, context):
    require(type(value) in (int, float) and math.isfinite(value), f"{context}: finite number required")
    return float(value)


def validate_aggregate(result):
    """Validate the common aggregate schema without assuming experiment identity."""
    require(result["seeds"] == list(SEEDS), f"Expected ordered seeds {SEEDS}")
    for model in MODELS:
        for split in SPLITS:
            for metric in ALL_METRICS:
                context = f"{model}/{split}/{metric}"
                summary = result["aggregate"][model][split][metric]
                require(len(summary["values"]) == 3, f"{context}: three seed values required")
                values = [finite_number(value, context) for value in summary["values"]]
                require(all(value >= 0 for value in values), f"{context}: negative error metric")
                for key, expected in (("mean", statistics.mean(values)), ("sample_std", statistics.stdev(values))):
                    actual = finite_number(summary[key], f"{context}/{key}")
                    require(math.isclose(actual, expected, rel_tol=1e-10, abs_tol=1e-10), f"{context}/{key}: inconsistent with seed values")
    paired = result["control_ood_paired"]
    require(paired["trajectory_count"] == 16, "OOD pairing must contain 16 trajectories")
    finite_number(paired["mean_difference_c"], "OOD mean difference")
    interval = paired["bootstrap_95_interval_c"]
    require(len(interval) == 2, "OOD interval must contain two endpoints")
    low, high = [finite_number(value, "OOD interval") for value in interval]
    require(low <= high, "OOD interval endpoints are reversed")
    for key in ("improved_trajectories", "worsened_trajectories"):
        require(type(paired[key]) is int and 0 <= paired[key] <= 16, f"Invalid {key}")
    require(paired["improved_trajectories"] + paired["worsened_trajectories"] <= 16, "OOD counts exceed trajectory count")


def render_table(result, grid):
    name, shape = GRIDS[grid]
    shape_tex = r"\times".join(str(value) for value in shape)
    lines = [
        "% Generated by render_paper_tables.py from the completed ZOH audit aggregate.",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        rf"\caption{{三维{name}网格 ${shape_tex}$ 的分段常值动作实验：三随机种子均值$\pm$样本标准差，单位均为 $^\circ\mathrm{{C}}$。}}",
        rf"\label{{tab:three-dimensional-zoh-{grid}}}",
        r"\begin{tabular}{llccc}",
        r"\toprule",
        r"划分 & 模型 & 滚动 RMSE & 终态平均 RMSE & 离散残差 RMSE \\",
        r"\midrule",
    ]
    for split, split_label in SPLITS.items():
        for model, model_label in MODELS.items():
            summaries = result["aggregate"][model][split]
            cells = [f"${summaries[metric]['mean']:.3f}\\pm{summaries[metric]['sample_std']:.3f}$" for metric in TABLE_METRICS]
            lines.append(" & ".join([split_label, model_label, *cells]) + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}", ""])
    return "\n".join(lines)


def grid_summary(result):
    paired = dict(result["control_ood_paired"])
    paired["tied_trajectories"] = paired["trajectory_count"] - paired["improved_trajectories"] - paired["worsened_trajectories"]
    comparisons = {}
    for split in SPLITS:
        comparisons[split] = {}
        for metric in ALL_METRICS:
            data = result["aggregate"]["data_only"][split][metric]["mean"]
            physics = result["aggregate"]["physics_constrained"][split][metric]["mean"]
            comparisons[split][metric] = {
                "data_mean": data,
                "physics_mean": physics,
                "physics_minus_data": physics - data,
                "reduction_percent": 100.0 * (data - physics) / data if data else None,
            }
    return {"control_ood_paired": paired, "metric_comparisons": comparisons}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", type=Path, default=DIRECTORY)
    parser.add_argument("--output-dir", type=Path, default=None, help="Default: input directory")
    args = parser.parse_args()
    input_dir = args.input_dir.resolve()
    output_dir = (args.output_dir or input_dir).resolve()
    inputs = {grid: input_dir / grid / INPUT_NAME for grid in GRIDS}
    missing = [str(path) for path in inputs.values() if not path.is_file()]
    if missing:
        parser.error("Both completed audit aggregates are required; missing: " + ", ".join(missing))

    protocol_path = input_dir / "protocol.json"
    protocol_hash = sha256(protocol_path)
    require((input_dir / "protocol.sha256").read_text().split()[0] == protocol_hash, "Frozen protocol hash mismatch")
    protocol = json.loads(protocol_path.read_text(encoding="utf-8"))
    require(protocol["training_seeds"] == list(SEEDS), "Unexpected protocol training seeds")
    require(protocol["split_counts"]["control_ood"] == 16, "Unexpected protocol OOD count")

    results = {}
    for grid, path in inputs.items():
        result = json.loads(path.read_text(encoding="utf-8"))
        validate_aggregate(result)
        require(result["grid"] == grid, f"{path}: grid mismatch")
        require(result["action_interpolation"] == "zero_order_hold", f"{path}: not the corrected ZOH audit")
        require(result["protocol_sha256"] == protocol_hash, f"{path}: protocol hash mismatch")
        require(protocol["grids"][grid]["shape"] == list(GRIDS[grid][1]), f"{grid}: unexpected grid shape")
        dataset_hash = result["dataset_sha256"]
        require(isinstance(dataset_hash, str) and len(dataset_hash) == 64 and all(c in "0123456789abcdef" for c in dataset_hash), f"{path}: invalid dataset hash")
        results[grid] = result

    summary = {
        "protocol_sha256": protocol_hash,
        "seeds": list(SEEDS),
        "temperature_error_unit": "degrees Celsius",
        "table_statistics": "Across three seeds: mean plus/minus sample standard deviation (ddof=1), rounded to 3 decimals only in LaTeX.",
        "paired_definition": "Physics minus data per-trajectory rollout RMSE, averaged over seeds before pairing; negative means improvement. Trajectories, not seeds, are bootstrap units; 100000 draws, seed 20260905. This differs from pooled rollout RMSE in the tables.",
        "reduction_definition": "100 * (data mean - physics mean) / data mean; positive means lower error, negative means higher error; null if data mean is zero. These are descriptive reductions, not confidence intervals.",
        "grids": {
            grid: {
                "shape": list(GRIDS[grid][1]),
                "input": str(inputs[grid]),
                "input_sha256": sha256(inputs[grid]),
                "dataset_sha256": result["dataset_sha256"],
                **grid_summary(result),
            }
            for grid, result in results.items()
        },
    }
    # Validate and render both grids before creating any output files.
    outputs = {f"three_dimensional_{grid}_table.tex": render_table(result, grid) for grid, result in results.items()}
    outputs["paper_tables_summary.json"] = json.dumps(summary, ensure_ascii=False, indent=2, allow_nan=False) + "\n"
    output_dir.mkdir(parents=True, exist_ok=True)
    for filename, content in outputs.items():
        (output_dir / filename).write_text(content, encoding="utf-8")
    print(json.dumps({"outputs": [str(output_dir / filename) for filename in outputs]}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
